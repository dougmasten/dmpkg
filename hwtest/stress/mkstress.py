#!/usr/bin/env python3
"""
Write the stress test's assets and the constants its loader checks them
with.

  mkstress.py

STRESS.DSK holds N = 256 assets of 8K, 2M in all, cut from one stream the
loader can work out for itself: a 16-bit Galois LFSR (taps $B400, period
65535), stepped once per byte, with its low byte as the data:

  lsb = s & 1;  s >>= 1;  if lsb: s ^= 0xB400;  byte = s & 0xFF

It starts from SEED at asset 0 and runs on from each asset into the next,
so a dropped, repeated or swapped byte, or the wrong asset, changes the
bytes. (The stream repeats every 65535 bytes, about every 8 assets, but one
byte further on each time, so asset k+8 still differs from asset k.)

The assets go to assets/ next to this script, and build/stress.inc gets
STRESS_N, STRESS_SIZE, STRESS_SEED and STRESS_TAPS.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
N = 256                                 # 2M; k fits in a byte
SIZE = 8192
SEED = 0xACE1                           # any nonzero state
TAPS = 0xB400                           # x^16 + x^14 + x^13 + x^11 + 1: maximal


def stream(n: int, seed: int = SEED) -> bytes:
    s, out = seed, bytearray(n)
    for i in range(n):
        lsb = s & 1
        s >>= 1
        if lsb:
            s ^= TAPS
        out[i] = s & 0xFF
    return bytes(out)


def main():
    assert 1 <= N <= 256, "stress.asm keeps the asset number in a byte"
    assert TAPS & 0xFF == 0, "stress.asm only flips the high byte"
    out = os.path.join(HERE, "assets")
    os.makedirs(out, exist_ok=True)
    data = stream(N * SIZE)
    for k in range(N):
        with open(os.path.join(out, f"s{k:03d}.bin"), "wb") as f:
            f.write(data[k * SIZE:(k + 1) * SIZE])
    build = os.path.join(HERE, "build")
    os.makedirs(build, exist_ok=True)
    with open(os.path.join(build, "stress.inc"), "w") as f:
        f.write("; Generated by hwtest/stress/mkstress.py - do not edit\n\n"
                f"STRESS_N        equ     {N}             ; assets, {SIZE} bytes each at $4000\n"
                f"STRESS_SIZE     equ     {SIZE}\n"
                f"STRESS_SEED     equ     ${SEED:04X}           ; LFSR state at asset 0\n"
                f"STRESS_TAPS     equ     ${TAPS >> 8:02X}             ; high byte of the taps ($B400)\n")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""
Write the stress test's assets and the checksums its loader checks them
against.

  mkstress.py

STRESS.DSK holds N = 64 assets of 8K, 512K in all. Asset k holds a rolling
pattern the loader can work out for itself:

  byte i = (i + i // 256 + 37 * k) mod 256        i = 0 .. 8191

so a dropped, repeated or swapped byte, or the wrong asset, changes the
bytes. The assets go to assets/ next to this script, and build/ssums.inc
gets STRESS_N, STRESS_STEP and a table of each asset's Fletcher
sums (fdb sum1,sum2: sum1 the 16-bit sum of the bytes, sum2 the 16-bit sum of
the running sum1 values), in asset order.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
N = 64
SIZE = 8192
STEP = 37                               # pattern offset from one asset to the next


def pattern(k: int) -> bytes:
    return bytes((i + (i >> 8) + STEP * k) & 0xFF for i in range(SIZE))


def sums(data: bytes) -> tuple[int, int]:
    s1 = s2 = 0
    for b in data:
        s1 = (s1 + b) & 0xFFFF
        s2 = (s2 + s1) & 0xFFFF
    return s1, s2


def main():
    out = os.path.join(HERE, "assets")
    os.makedirs(out, exist_ok=True)
    lines = ["; Generated by hwtest/stress/mkstress.py - do not edit", "",
             f"STRESS_N        equ     {N}             ; assets, {SIZE} bytes each at $4000",
             f"STRESS_SIZE     equ     {SIZE}",
             f"STRESS_STEP     equ     {STEP}             ; byte i of asset k: i + i/256 + STEP*k",
             "", "StressSums                              ; fdb sum1,sum2 per asset"]
    for k in range(N):
        data = pattern(k)
        with open(os.path.join(out, f"s{k:02d}.bin"), "wb") as f:
            f.write(data)
        s1, s2 = sums(data)
        lines.append(f"        fdb     ${s1:04X},${s2:04X}         ; s{k:02d}")
    build = os.path.join(HERE, "build")
    os.makedirs(build, exist_ok=True)
    with open(os.path.join(build, "ssums.inc"), "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()

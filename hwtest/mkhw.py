#!/usr/bin/env python3
"""
Write the hardware test's assets and the checksums its loader checks them
against.

  mkhw.py [--seed N]

Assets go to hwtest/assets/ (random filler, fixed seed). Then every asset of
disk.yaml, big.yaml and stream.yaml gets a checksum entry in
hwtest/build/hwsums.inc, labelled <symbol>_SUM:

  fcb  regions                   1, or one per segment of a decb asset
  then per region:
  fcb  flags                     $80: phys address (CoCo 3)
  fcb  addr(3)                   CPU or physical address
  fdb  length, sum1, sum2        Fletcher-style sums of the bytes

sum1 is the 16-bit sum of the bytes, sum2 the 16-bit sum of the running
sum1 values, so the check catches bytes in the wrong order or place, not
just wrong bytes. Needs the dmpkg package (PYTHONPATH=python/src).
"""
import argparse
import os
import random

from dmpkg import decb, image, layout, manifest

HERE = os.path.dirname(os.path.abspath(__file__))
SEED = 6309
RAW = {"a_odd.bin": 767, "b_pack.bin": 300, "c_multi.bin": 1500, "d_align.bin": 513,
       "f_phys.bin": 20001, "tail.bin": 10000, "s_data.bin": 600, "s_align.bin": 700,
       "t_blk.bin": 512, "t_run.bin": 16 * 512}
FILL = 160 * 1024                       # big.yaml only: never loaded
CODE_SEGS = ((0x3E00, 64), (0x3F00, 77))
CODE = bytes([0xCC, 0x60, 0x0D, 0x39])  # ldd #$600D / rts: what EXEC expects back
MANIFESTS = ("disk.yaml", "big.yaml", "stream.yaml")


def rand_bytes(rng, n):
    return rng.getrandbits(8 * n).to_bytes(n, "little")


def assets(rng):
    files = {n: rand_bytes(rng, size) for n, size in RAW.items()}
    files["fill.bin"] = bytes(FILL)
    code = b""
    for i, (addr, n) in enumerate(CODE_SEGS):
        data = rand_bytes(rng, n)
        if i == 0:
            data = CODE + data[len(CODE):]
        code += b"\x00" + n.to_bytes(2, "big") + addr.to_bytes(2, "big") + data
    files["e_code.bin"] = code + b"\xff\x00\x00" + CODE_SEGS[0][0].to_bytes(2, "big")
    return files


def sums(data):
    s1 = s2 = 0
    for b in data:
        s1 = (s1 + b) & 0xFFFF
        s2 = (s2 + s1) & 0xFFFF
    return s1, s2


def entry(sym, regions):
    lines = [f"{sym}_SUM", f"        fcb     {len(regions)}"]
    for phys, addr, data in regions:
        s1, s2 = sums(data)
        lines.append(f"        fcb     ${0x80 if phys else 0:02X},${addr >> 16:02X},"
                     f"${(addr >> 8) & 0xFF:02X},${addr & 0xFF:02X}")
        lines.append(f"        fdb     ${len(data):04X},${s1:04X},${s2:04X}")
    return lines


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0].strip())
    ap.add_argument("--seed", type=int, default=SEED)
    a = ap.parse_args()

    out = os.path.join(HERE, "assets")
    os.makedirs(out, exist_ok=True)
    for name, data in assets(random.Random(a.seed)).items():
        with open(os.path.join(out, name), "wb") as f:
            f.write(data)

    # big.yaml: GAP takes the space disk.yaml's assets leave before track 17,
    # except granules 31-33 (HWBIG.BIN and AUTOEXEC.BAS). TAIL is too big for
    # those, so it goes after FILL, past track 34
    _, items = manifest.load(os.path.join(HERE, "disk.yaml"), loader=False)
    data0 = image.toc_size(len(items) + 3)[1] * image.BLOCK
    layout.place(items, data0, True)
    end = max(a.pos + len(a.data) for a in items)
    with open(os.path.join(out, "gap.bin"), "wb") as f:
        f.write(bytes(decb.gran_offset(31) - end))

    lines = ["; Generated by hwtest/mkhw.py - do not edit", ""]
    done = set()
    for m in MANIFESTS:
        project, items = manifest.load(os.path.join(HERE, m), loader=False)
        for asset in items:
            sym = project.prefix + asset.name
            if sym in done:
                continue
            done.add(sym)
            if asset.kind == "decb":
                regions = [(False, addr, data) for addr, data in asset.segs]
            else:
                regions = [(asset.phys, asset.dest, asset.data)]
            lines += entry(sym, regions) + [""]
    os.makedirs(os.path.join(HERE, "build"), exist_ok=True)
    with open(os.path.join(HERE, "build", "hwsums.inc"), "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
